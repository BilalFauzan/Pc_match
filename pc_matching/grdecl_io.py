"""
pc_matching.grdecl_io
=====================
High-performance parser and writer for ECLIPSE / Petrel / tNavigator
GRDECL format files. Optimised with byte-level streaming and run-length
decoding for grids with tens of millions of cells.
"""

import os
import re
import numpy as np
from typing import Tuple, Optional, Dict, Any, List


class FastGRDECLParser:
    """
    High-speed binary and text parser for Petrel / Eclipse GRDECL property decks.
    """

    @staticmethod
    def scan_keywords(filepath: str) -> List[Tuple[int, str]]:
        """
        Scan a GRDECL file for all keyword definitions.
        Returns a list of (line_number, keyword_name).
        """
        keywords = []
        with open(filepath, 'r', errors='ignore') as f:
            for line_idx, line in enumerate(f, start=1):
                clean = line.strip()
                if not clean or clean.startswith('--'):
                    continue
                match = re.match(r'^([A-Z][A-Z0-9_]{1,15})\b', clean)
                if match:
                    kw = match.group(1)
                    if not re.match(r'^\d', kw) and '*' not in clean[:8] and '.' not in kw:
                        keywords.append((line_idx, kw))
        return keywords

    @staticmethod
    def parse_property(
        filepath: str,
        keyword: str,
        total_cells: Optional[int] = None,
        dtype=np.float32
    ) -> np.ndarray:
        """
        Parse a 3D grid property array from a GRDECL file using byte-level token stream.
        Handles Eclipse RLE (Run-Length Encoding) e.g., '1000*0.25' or '50*0'.
        
        Parameters
        ----------
        filepath : str
            Path to the .GRDECL file.
        keyword : str
            Keyword name to parse (e.g., 'RT_HM', 'DEPTH', 'PORO', 'SWAT').
        total_cells : int, optional
            Expected total cells. If specified, pre-allocates memory for speed.
        dtype : data-type, optional
            NumPy data type (default: np.float32).
            
        Returns
        -------
        np.ndarray
            1D array of property values.
        """
        kw_bytes = keyword.strip().encode('ascii')
        
        # Initial allocation
        initial_cap = total_cells if total_cells is not None else 1_000_000
        arr = np.zeros(initial_cap, dtype=dtype)
        idx = 0
        in_prop = False

        with open(filepath, 'rb') as f:
            for line in f:
                line_clean = line.strip()
                if not in_prop:
                    if line_clean.startswith(kw_bytes):
                        # Verify exact word boundary
                        tokens = line_clean.split()
                        if tokens and tokens[0] == kw_bytes:
                            in_prop = True
                            continue
                else:
                    if not line_clean or line_clean.startswith(b'--'):
                        continue
                    tokens = line_clean.split()
                    for tok in tokens:
                        if tok == b'/':
                            return arr[:idx]
                        if b'*' in tok:
                            star_idx = tok.index(b'*')
                            n = int(tok[:star_idx])
                            v = float(tok[star_idx + 1:])
                            req_len = idx + n
                            if req_len > len(arr):
                                new_size = max(req_len, len(arr) * 2)
                                arr = np.resize(arr, new_size)
                            if v != 0.0:
                                arr[idx:req_len] = v
                            idx += n
                        else:
                            v = float(tok)
                            if idx >= len(arr):
                                arr = np.resize(arr, max(idx + 1000, len(arr) * 2))
                            if v != 0.0:
                                arr[idx] = v
                            idx += 1

        return arr[:idx]

    @staticmethod
    def write_property(
        filepath: str,
        keyword: str,
        array: np.ndarray,
        comment: Optional[str] = None,
        compress_rle: bool = True,
        values_per_line: int = 6,
        format_spec: str = '16.8f'
    ) -> None:
        """
        Write a NumPy array to a valid ECLIPSE / tNavigator GRDECL property deck.
        Optionally compresses repeated values into RLE format 'n*value'.
        """
        with open(filepath, 'w') as f:
            f.write(f"-- Generated by Pc-Matching Application\n")
            if comment:
                f.write(f"-- {comment}\n")
            f.write(f"\n{keyword.upper()}\n")

            if not compress_rle:
                # Raw output
                count = 0
                for v in array:
                    f.write(f" {v:{format_spec}}")
                    count += 1
                    if count % values_per_line == 0:
                        f.write("\n")
                f.write(" /\n")
            else:
                # Run-length encoded output
                n_total = len(array)
                i = 0
                line_tokens = []
                while i < n_total:
                    val = array[i]
                    run_len = 1
                    while i + run_len < n_total and array[i + run_len] == val:
                        run_len += 1
                    i += run_len

                    # Format token
                    val_str = f"{val:.6g}" if abs(val) < 1e-4 or abs(val) > 1e4 else f"{val:.6f}".rstrip('0').rstrip('.')
                    if val_str == '-0':
                        val_str = '0'
                    if run_len > 1:
                        tok = f"{run_len}*{val_str}"
                    else:
                        tok = val_str

                    line_tokens.append(tok)
                    if len(line_tokens) >= values_per_line:
                        f.write("  " + " ".join(line_tokens) + "\n")
                        line_tokens = []

                if line_tokens:
                    f.write("  " + " ".join(line_tokens) + "\n")
                f.write(" /\n")


    @staticmethod
    def parse_density_keyword(filepath: str) -> List[Dict[str, float]]:
        """
        Parse DENSITY keyword records from ECLIPSE PROPS include file.
        Returns list of dicts: [{'oil_density': float, 'water_density': float, 'gas_density': float}, ...]
        """
        with open(filepath, 'r', errors='ignore') as f:
            lines = f.readlines()
        
        in_kw = False
        records = []
        current_tokens = []
        stop_keywords = {'FILLEPS', 'SWOF', 'SGOF', 'ROCK', 'PVTO', 'PVTW', 'PVDG', 'PROPS'}
        
        for line in lines:
            clean = line.split('--')[0].strip()
            if not clean:
                continue
            tokens = clean.split()
            if not in_kw:
                if tokens and tokens[0].upper() == 'DENSITY':
                    in_kw = True
                    tokens = tokens[1:]
            if in_kw:
                if tokens and tokens[0].upper() in stop_keywords:
                    break
                for t in tokens:
                    if t == '/':
                        if current_tokens:
                            records.append(current_tokens)
                            current_tokens = []
                    elif t.endswith('/'):
                        current_tokens.append(t[:-1])
                        records.append(current_tokens)
                        current_tokens = []
                    else:
                        current_tokens.append(t)
        
        parsed = []
        for r in records:
            vals = [float(x) for x in r if x]
            if len(vals) >= 2:
                parsed.append({
                    'oil_density': vals[0],
                    'water_density': vals[1],
                    'gas_density': vals[2] if len(vals) > 2 else None
                })
        return parsed

    @staticmethod
    def parse_equil_keyword(filepath: str) -> List[Dict[str, Any]]:
        """
        Parse EQUIL keyword records from ECLIPSE SOLUTION include file.
        Returns list of dicts for each equilibration region.
        """
        with open(filepath, 'r', errors='ignore') as f:
            lines = f.readlines()
        
        in_kw = False
        records = []
        current_tokens = []
        stop_keywords = {'RPTRST', 'RPTSOL', 'SOLUTION', 'SUMMARY', 'SCHEDULE'}
        
        for line in lines:
            clean = line.split('--')[0].strip()
            if not clean:
                continue
            tokens = clean.split()
            if not in_kw:
                if tokens and tokens[0].upper() == 'EQUIL':
                    in_kw = True
                    tokens = tokens[1:]
            if in_kw:
                if tokens and tokens[0].upper() in stop_keywords:
                    break
                for t in tokens:
                    if t == '/':
                        if current_tokens:
                            records.append(current_tokens)
                            current_tokens = []
                    elif t.endswith('/'):
                        current_tokens.append(t[:-1])
                        records.append(current_tokens)
                        current_tokens = []
                    else:
                        current_tokens.append(t)
        
        parsed = []
        for idx, r in enumerate(records, start=1):
            vals = [float(x) for x in r[:6] if x]
            if len(vals) >= 3:
                parsed.append({
                    'region': idx,
                    'datum_depth': vals[0],
                    'datum_pressure': vals[1],
                    'woc_depth': vals[2],
                    'pc_woc': vals[3] if len(vals) > 3 else 0.0,
                    'goc_depth': vals[4] if len(vals) > 4 else vals[0],
                    'pc_goc': vals[5] if len(vals) > 5 else 0.0
                })
        return parsed


def extract_active_reservoir(
    rt_array: np.ndarray,
    poro_array: np.ndarray,
    ntg_array: Optional[np.ndarray] = None,
    min_poro: float = 0.001
) -> Tuple[np.ndarray, Dict[str, Any]]:
    """
    Generate boolean mask and statistics for active reservoir cells.
    
    Active cells are defined by:
    1. Rock Type > 0 (valid reservoir rock type)
    2. Porosity > min_poro (permeable/storage pay)
    3. NTG > 0 (if NTG is supplied)
    """
    mask = (rt_array > 0) & (poro_array >= min_poro)
    if ntg_array is not None:
        mask = mask & (ntg_array > 0)

    stats = {
        'total_grid_cells': len(rt_array),
        'active_reservoir_cells': int(np.sum(mask)),
        'active_fraction': float(np.sum(mask) / len(rt_array)),
        'rock_type_counts': {
            int(rt): int(np.sum(mask & (rt_array == rt)))
            for rt in np.unique(rt_array[mask])
        }
    }
    return mask, stats

